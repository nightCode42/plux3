# Writes the Homebrew formula and the Scoop manifest of a CLI release from
# its SHA256SUMS (CLI-001). Both download the release archive from GitHub
# and pin its hash; the maintainer copies them into the tap and bucket
# repositories when publishing a release.
#
#   package-manifests.sh <version> <dist-dir>
set -eu
version=$1 dist=$2
repo=${PLUX_RELEASE_REPO:-nightCode42/plux3}
base="https://github.com/$repo/releases/download/backend%2Fv$version"
sum() { awk -v f="plux_${version}_$1" '$2 == f { print $1 }' "$dist/SHA256SUMS"; }

cat > "$dist/plux.rb" <<RUBY
# Generated by scripts/release/package-manifests.sh for plux $version.
class Plux < Formula
  desc "Command-line interface for Plux, the server-driven UI platform for Flutter"
  homepage "https://github.com/$repo"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$base/plux_${version}_darwin_arm64.tar.gz"
      sha256 "$(sum darwin_arm64.tar.gz)"
    end
    on_intel do
      url "$base/plux_${version}_darwin_amd64.tar.gz"
      sha256 "$(sum darwin_amd64.tar.gz)"
    end
  end
  on_linux do
    on_arm do
      url "$base/plux_${version}_linux_arm64.tar.gz"
      sha256 "$(sum linux_arm64.tar.gz)"
    end
    on_intel do
      url "$base/plux_${version}_linux_amd64.tar.gz"
      sha256 "$(sum linux_amd64.tar.gz)"
    end
  end

  def install
    bin.install "plux"
    generate_completions_from_executable(bin/"plux", "completion")
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/plux version")
  end
end
RUBY

cat > "$dist/plux.json" <<JSON
{
  "version": "$version",
  "description": "Command-line interface for Plux, the server-driven UI platform for Flutter",
  "homepage": "https://github.com/$repo",
  "license": "Apache-2.0",
  "architecture": {
    "64bit": {
      "url": "$base/plux_${version}_windows_amd64.zip",
      "hash": "$(sum windows_amd64.zip)",
      "extract_dir": "plux_${version}_windows_amd64"
    },
    "arm64": {
      "url": "$base/plux_${version}_windows_arm64.zip",
      "hash": "$(sum windows_arm64.zip)",
      "extract_dir": "plux_${version}_windows_arm64"
    }
  },
  "bin": "plux.exe"
}
JSON
echo "Wrote $dist/plux.rb and $dist/plux.json"
