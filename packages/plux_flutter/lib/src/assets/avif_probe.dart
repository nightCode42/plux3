/// Whether AVIF images decode here; never throws.
Future<bool> decodesAvif() async {
  try {
    final codec = await ui.instantiateImageCodec(_probe);
    try {
      final frame = await codec.getNextFrame();
      final ok = frame.image.width == 1 && frame.image.height == 1;
      frame.image.dispose();
      return ok;
    } finally {
      codec.dispose();
    }
  } on Object {
    return false;
  }
}
