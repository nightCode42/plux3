// repoRoot is the repository the tests check the real rules against.
var repoRoot = filepath.Join("..", "..", "..")

func projectRules(t *testing.T) *Rules {
	t.Helper()
	r, err := Load(repoRoot, filepath.Join(repoRoot, "ci", "affected.json"))
	if err != nil {
		t.Fatal(err)
	}
	return r
}

func projectWorkflow(t *testing.T) string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(repoRoot, filepath.FromSlash(WorkflowPath)))
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

func trackedFiles(t *testing.T) []string {
	t.Helper()
	out, err := exec.CommandContext(t.Context(), "git", "-C", repoRoot, "ls-files", "-z").Output() //nolint:gosec // G204: git on this repository.
	if err != nil {
		t.Fatalf("git ls-files: %v", err)
	}
	var files []string
	for f := range bytes.SplitSeq(out, []byte{0}) {
		if len(f) > 0 {
			files = append(files, string(f))
		}
	}
	return files
}

// TestProjectRulesMatchTheWorkflow checks that ci/affected.json and
// ci.yml agree: every job of the workflow either always runs or has a
// rule, every rule names a job of the workflow, every selectable job runs
// only when the selection says so, and CI OK waits for every job.
// Verifies: CI-002.
func TestProjectRulesMatchTheWorkflow_CI_002(t *testing.T) {
	t.Parallel()
	rules := projectRules(t)
	text := projectWorkflow(t)
	_, blocks := workflowBlocks(text)
	known := map[string]bool{}
	for _, id := range rules.Always() {
		known[id] = true
		if _, ok := blocks[id]; !ok {
			t.Errorf("ci/affected.json: always-on job %s is not in %s", id, WorkflowPath)
		}
	}
	for _, job := range rules.Jobs() {
		known[job.CI] = true
		block, ok := blocks[job.CI]
		if !ok {
			t.Errorf("ci/affected.json: job %s names %s, which is not in %s", job.Name, job.CI, WorkflowPath)
			continue
		}
		if job.Name == job.CI && !strings.Contains(block, "fromJSON(needs.changes.outputs.jobs)['"+job.Name+"']") {
			t.Errorf("%s: job %s does not run on fromJSON(needs.changes.outputs.jobs)['%s']", WorkflowPath, job.CI, job.Name)
		}
		if job.Name != job.CI && !strings.Contains(text, "'"+job.Name+"'") {
			t.Errorf("%s never reads the selection of %s", WorkflowPath, job.Name)
		}
	}
	needs := blocks["ci-ok"]
	for id := range blocks {
		if !known[id] {
			t.Errorf("%s: job %s neither always runs nor has a rule in ci/affected.json", WorkflowPath, id)
		}
		if id != "ci-ok" && !regexp.MustCompile(`(?m)^      - `+regexp.QuoteMeta(id)+`$`).MatchString(needs) {
			t.Errorf("%s: CI OK does not wait for %s", WorkflowPath, id)
		}
	}
}

// TestProjectRulesNameEveryTrackedFile checks that every file in the
// repository is named by a rule, so that today no change falls back to
// running everything for want of a rule; a new kind of file must be
// added to ci/affected.json.
// Verifies: CI-002.
func TestProjectRulesNameEveryTrackedFile_CI_002(t *testing.T) {
	t.Parallel()
	rules := projectRules(t)
	for _, f := range trackedFiles(t) {
		if rules.everything.Contains(f) || rules.noJob.Contains(f) {
			continue
		}
		named := false
		for _, job := range rules.Jobs() {
			if job.why(f) != nil {
				named = true
				break
			}
		}
		if !named {
			t.Errorf("no rule in ci/affected.json names %s", f)
		}
	}
}

// TestProjectGeneratedFilesRunGoLint checks that a change to any file
// `make gen` writes runs the job that regenerates them (CI-003).
func TestProjectGeneratedFilesRunGoLint(t *testing.T) {
	t.Parallel()
	rules := projectRules(t)
	var lint *Job
	for _, job := range rules.Jobs() {
		if job.Name == "go-lint" {
			lint = job
		}
	}
	if lint == nil {
		t.Fatal("ci/affected.json has no go-lint job")
	}
	markers := [][]byte{[]byte("Code generated"), []byte("DO NOT EDIT"), []byte("automatically generated by the FlatBuffers compiler")}
	genPaths := []string{"backend/", "tools/", "docs/reference/", "packages/", "studio/packages/", "schema/"}
	for _, f := range trackedFiles(t) {
		if !slices.ContainsFunc(genPaths, func(p string) bool { return strings.HasPrefix(f, p) }) {
			continue
		}
		data, err := os.ReadFile(filepath.Join(repoRoot, filepath.FromSlash(f)))
		if err != nil {
			t.Fatal(err)
		}
		head := data[:min(len(data), 2048)]
		if slices.ContainsFunc(markers, func(m []byte) bool { return bytes.Contains(head, m) }) && lint.why(f) == nil {
			t.Errorf("%s is generated, but a change to it does not run go-lint", f)
		}
	}
}

// TestProjectPastChangesRunTheRightJobs checks the selection against real
// changes from the repository's history and typical changes, each with
// the exact jobs it must run.
// Verifies: CI-002.
func TestProjectPastChangesRunTheRightJobs_CI_002(t *testing.T) {
	t.Parallel()
	rules := projectRules(t)
	text := projectWorkflow(t)
	var all []string
	for _, job := range rules.Jobs() {
		all = append(all, job.Name)
	}
	goServer := []string{"bench-sync", "compose", "e2e-android", "e2e-ios", "go-lint", "go-test", "starter-e2e"}
	runtime := []string{"bench-runtime", "bench-sync", "dart", "e2e-android", "e2e-ios", "size-android", "size-ios", "starter-e2e"}
	cases := []struct {
		name  string
		files []string
		head  string // ci.yml at the head when it differs from today's
		want  []string
	}{
		{
			name: "PR #13: README, logo and spec 1.1.9 (a Go test reads the spec)",
			files: []string{
				"README.md", "docs/WORKLOG.md", "docs/assets/brand/plux-icon.svg", "docs/assets/readme/how-it-works-dark.svg",
				"docs/requirements.md", "docs/worklog-archive.md",
			},
			want: []string{"go-test"},
		},
		{
			name:  "PR #12: the Phase 4 plan",
			files: []string{"docs/WORKLOG.md", "docs/plans/p4.md", "docs/worklog-archive.md", "site/src/loader.ts"},
			want:  nil,
		},
		{
			name: "PR #11 as merged: the root Makefile's header (GNU Make 4 guard) and the macOS jobs",
			files: []string{
				".github/workflows/ci.yml", "Makefile", "README.md", "docs/WORKLOG.md", "docs/engineering/testing.md",
				"docs/guides/run-locally.md", "docs/worklog-archive.md", "scripts/test-db.sh",
			},
			want: all,
		},
		{
			name: "PR #11's make test-db alone, in today's fragments",
			files: []string{
				"mk/stack.mk", "scripts/test-db.sh", "docs/engineering/testing.md", "docs/guides/run-locally.md", "docs/WORKLOG.md",
			},
			want: []string{"compose", "image-arm64"},
		},
		{
			name: "PR #10: retry the pathops downloads, the Run it locally guide",
			files: []string{
				"README.md", "docs/WORKLOG.md", "docs/guides/first-release.md", "docs/guides/run-locally.md", "docs/worklog-archive.md",
				"packages/plux_svgc/native/build.sh", "site/astro.config.mjs", "site/src/content/docs/index.md",
			},
			want: []string{"compose", "dart", "image-arm64"},
		},
		{
			name:  "PR #8: the test database in cloud sessions",
			files: []string{"docs/engineering/testing.md", "scripts/session-start.sh"},
			want:  nil,
		},
		{
			name:  "a compiler change",
			files: []string{"backend/internal/compiler/compiler.go"},
			want:  sorted(append([]string{"go-build", "go-determinism", "go-vuln", "image-arm64"}, goServer...)),
		},
		{
			name:  "a server test",
			files: []string{"backend/internal/server/objects_test.go"},
			want:  goServer,
		},
		{
			name:  "a tool",
			files: []string{"tools/cmd/sizegate/main.go"},
			want:  []string{"go-lint", "go-test", "go-vuln", "size-android", "size-ios"},
		},
		{
			name:  "the runtime's rendering",
			files: []string{"packages/plux_flutter/lib/src/render/decoders.dart"},
			want:  runtime,
		},
		{
			name:  "a runtime test",
			files: []string{"packages/plux_flutter/test/render_test.dart"},
			want:  []string{"dart"},
		},
		{
			name:  "the runtime's Android plugin",
			files: []string{"packages/plux_flutter/android/build.gradle.kts"},
			want:  []string{"dart", "e2e-android", "e2e-android-26", "size-android"},
		},
		{
			name:  "a Dart-only package",
			files: []string{"packages/plux_widget_api/bin/extract.dart"},
			want:  []string{"dart"},
		},
		{
			name:  "Studio",
			files: []string{"studio/biome.json"},
			want:  []string{"studio"},
		},
		{
			name:  "the Dart job's block of ci.yml",
			files: []string{WorkflowPath},
			head:  strings.Replace(text, "Flutter snapshot matches the pinned SDK", "Flutter snapshot matches the pinned Flutter SDK", 1),
			want:  []string{"dart", "go-test"},
		},
		{
			name:  "ci.yml's env",
			files: []string{WorkflowPath},
			head:  strings.Replace(text, "env:\n", "env:\n  NEW: 1\n", 1),
			want:  all,
		},
		{
			name:  "a new top-level directory",
			files: []string{"newdir/file"},
			want:  all,
		},
	}
	for _, c := range cases {
		head := text
		if c.head != "" {
			if c.head == text {
				t.Fatalf("%s: the edit to ci.yml changed nothing", c.name)
			}
			head = c.head
		}
		res := rules.Select(Change{Event: "pull_request", Files: c.files, BaseWorkflow: text, HeadWorkflow: head})
		if got := res.Selected(); !slices.Equal(got, c.want) {
			t.Errorf("%s:\n got  %v\n want %v\n%s", c.name, got, c.want, res.Summary(rules.Always()))
		}
	}
}

func sorted(s []string) []string {
	slices.Sort(s)
	return s
}
