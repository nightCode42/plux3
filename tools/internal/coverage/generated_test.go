package coverage

import (
	"path/filepath"
	"reflect"
	"strings"
	"testing"
)

// TestDropGeneratedRemovesMarkedFilesOnly checks that files with a generated
// marker in their header are excluded from coverage and all others are kept.
// Verifies: QA-001.
func TestDropGeneratedRemovesMarkedFilesOnly(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	spdx := "// SPDX-FileCopyrightText: 2026 Plux contributors\n// SPDX-License-Identifier: Apache-2.0\n\n"
	files := map[string]string{
		"backend/gen/model_gen.go":     spdx + "// Code generated by schemagen. DO NOT EDIT.\n\npackage gen\n",
		"backend/fbs/Page.go":          "// Code generated by the FlatBuffers compiler. DO NOT EDIT.\n\npackage fbs\n",
		"lib/src/bundle/page.dart":     "// automatically generated by the FlatBuffers compiler, do not modify\n",
		"backend/pxl/vm.go":            spdx + "package pxl\n",
		"backend/pxl/mentions_gen.go":  spdx + "package pxl\n\n// This file is not generated; it only says: Code generated ... DO NOT EDIT.\n",
		"backend/pxl/deep_marker.go":   spdx + strings.Repeat("//\n", headerLines) + "// Code generated by x. DO NOT EDIT.\n",
		"studio/packages/schema/a.ts":  "// Code generated by schemagen. DO NOT EDIT.\nexport {};\n",
		"studio/packages/schema/b.ts":  "export const b = 1;\n",
		"backend/pxl/almost_marker.go": "// Code generated by schemagen. DO NOT EDIT\npackage pxl\n",
	}
	var input []FileCoverage
	for path, content := range files {
		write(t, filepath.Join(root, filepath.FromSlash(path)), content)
		input = append(input, FileCoverage{Path: path, Total: 10, Covered: 5})
	}
	input = append(input, FileCoverage{Path: "backend/pxl/deleted.go", Total: 1})

	kept, dropped, err := DropGenerated(input, root)
	if err != nil {
		t.Fatal(err)
	}

	var got []string
	for _, f := range kept {
		got = append(got, f.Path)
	}
	want := map[string]bool{
		"backend/pxl/vm.go": true, "backend/pxl/mentions_gen.go": true, "backend/pxl/deep_marker.go": true,
		"studio/packages/schema/b.ts": true, "backend/pxl/almost_marker.go": true, "backend/pxl/deleted.go": true,
	}
	gotSet := map[string]bool{}
	for _, p := range got {
		gotSet[p] = true
	}
	if !reflect.DeepEqual(gotSet, want) {
		t.Errorf("kept = %v, want %v", got, want)
	}
	if dropped != 4 {
		t.Errorf("dropped = %d, want 4", dropped)
	}
}
