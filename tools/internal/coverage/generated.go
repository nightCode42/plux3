package coverage

import (
	"bufio"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
)

// generatedMarker matches the header line that marks a file as generated:
// the Go convention (https://go.dev/s/generatedcode), which Plux generators
// also write into Dart and TypeScript files, and the fixed header of the
// Dart code emitted by flatc.
var generatedMarker = regexp.MustCompile(
	`^// (Code generated .* DO NOT EDIT\.|automatically generated by the FlatBuffers compiler, do not modify)$`)

// headerLines is how far into a file the marker is searched for. Generated
// files put it right after the licence header.
const headerLines = 30

// DropGenerated removes files marked as generated, so that coverage floors
// measure hand-written code only. Generated code is verified by regenerating
// it (CI-003), not by tests. Paths are resolved against repoRoot; a file that
// no longer exists is kept, since its coverage was measured.
func DropGenerated(files []FileCoverage, repoRoot string) (kept []FileCoverage, dropped int, err error) {
	kept = make([]FileCoverage, 0, len(files))
	for _, f := range files {
		gen, err := isGenerated(filepath.Join(repoRoot, filepath.FromSlash(f.Path)))
		if err != nil {
			return nil, 0, err
		}
		if gen {
			dropped++
			continue
		}
		kept = append(kept, f)
	}
	return kept, dropped, nil
}

// isGenerated reports whether the file's header carries the generated marker.
func isGenerated(path string) (bool, error) {
	f, err := os.Open(path)
	if errors.Is(err, fs.ErrNotExist) {
		return false, nil
	}
	if err != nil {
		return false, fmt.Errorf("coverage.isGenerated: %w", err)
	}
	defer func() { _ = f.Close() }()
	scanner := bufio.NewScanner(f)
	for i := 0; i < headerLines && scanner.Scan(); i++ {
		if generatedMarker.MatchString(scanner.Text()) {
			return true, nil
		}
	}
	if err := scanner.Err(); err != nil {
		return false, fmt.Errorf("coverage.isGenerated %s: %w", path, err)
	}
	return false, nil
}
