// Command gennames writes the icon name tables of package icons from the
// fonts' name lists: <set>.codepoints ("<name> <hex code point>" lines)
// and mirrored.txt ("<set> <name>" lines).
package main

import (
	"bufio"
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

type glyph struct {
	name     string
	code     uint64
	mirrored bool
}

func main() {
	dir := flag.String("dir", "fonts", "the directory of the name lists")
	out := flag.String("out", "names_gen.go", "the Go file to write")
	flag.Parse()
	if err := run(*dir, *out); err != nil {
		fmt.Fprintln(os.Stderr, "gennames:", err)
		os.Exit(1)
	}
}

func run(dir, out string) error {
	mirrored, err := readMirrored(filepath.Join(dir, "mirrored.txt"))
	if err != nil {
		return err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by gennames from fonts/*.codepoints and fonts/mirrored.txt. DO NOT EDIT.\n\n")
	b.WriteString("package icons\n")
	for _, set := range []string{"material", "cupertino"} {
		glyphs, err := readCodepoints(filepath.Join(dir, set+".codepoints"), mirrored[set])
		if err != nil {
			return err
		}
		fmt.Fprintf(&b, "\n// %sGlyphs are the icons of the %s set, sorted by name.\nvar %sGlyphs = []Glyph{\n", set, set, set)
		for _, g := range glyphs {
			fmt.Fprintf(&b, "\t{%q, 0x%x, %t},\n", g.name, g.code, g.mirrored)
		}
		b.WriteString("}\n")
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("format: %w", err)
	}
	if err := os.WriteFile(out, src, 0o644); err != nil { //nolint:gosec // generated source, world-readable like every other
		return fmt.Errorf("write: %w", err)
	}
	return nil
}

func readMirrored(path string) (map[string]map[string]bool, error) {
	data, err := os.ReadFile(path) //nolint:gosec // a path of this repository
	if err != nil {
		return nil, fmt.Errorf("read: %w", err)
	}
	out := map[string]map[string]bool{}
	for line := range strings.Lines(string(data)) {
		set, name, ok := strings.Cut(strings.TrimSpace(line), " ")
		if !ok {
			return nil, fmt.Errorf("%s: bad line %q", path, line)
		}
		if out[set] == nil {
			out[set] = map[string]bool{}
		}
		out[set][name] = true
	}
	return out, nil
}

func readCodepoints(path string, mirrored map[string]bool) ([]glyph, error) {
	f, err := os.Open(path) //nolint:gosec // a path of this repository
	if err != nil {
		return nil, fmt.Errorf("open: %w", err)
	}
	defer f.Close() //nolint:errcheck // read only
	var out []glyph
	seen := map[string]bool{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		name, hex, ok := strings.Cut(strings.TrimSpace(sc.Text()), " ")
		if !ok {
			return nil, fmt.Errorf("%s: bad line %q", path, sc.Text())
		}
		code, err := strconv.ParseUint(hex, 16, 32)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		if seen[name] {
			return nil, fmt.Errorf("%s: %s is listed twice", path, name)
		}
		seen[name] = true
		out = append(out, glyph{name, code, mirrored[name]})
	}
	if err := sc.Err(); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	if len(out) == 0 {
		return nil, errors.New(path + " lists no icons")
	}
	slices.SortFunc(out, func(a, b glyph) int { return strings.Compare(a.name, b.name) })
	return out, nil
}
