const stateClass = `
/// A typed handle on an exposed app state entry (STA-030).
final class PluxTypedState<T> {
  const PluxTypedState._(this.name, this._decode, this._encode);

  /// The entry's name.
  final String name;

  final T Function(Object? json) _decode;
  final Object? Function(T value) _encode;

  plux.PluxState<Object?> get _state => plux.Plux.state<Object?>(name);

  /// The current value; null before a release is active.
  T? get value {
    final v = _state.value;
    return v == null ? null : _decode(v);
  }

  /// Writes [value]; completes with whether it was accepted.
  Future<bool> set(T value) => _state.set(_encode(value));

  /// One value per change.
  Stream<T?> watch() =>
      _state.watch().map((v) => v == null ? null : _decode(v));
}
`
